import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import mysql from 'mysql2/promise';
import { databaseConfig, projectRoot } from '../src/config.js';
import { tenantDatabaseName } from '../src/database.js';
import { tenantStore, closePreventionPools } from '../src/prevention/mysql-store.js';
import { Agenda } from '../src/prevention/agenda.js';
import { HearingScheduler } from '../src/prevention/scheduler.js';
import { registerStation } from '../src/prevention/diagnostics.js';
import { EscalationOutbox } from '../src/prevention/escalation.js';

const tenantId = randomUUID();
const database = tenantDatabaseName(tenantId);
const { registryDatabase, ...connection } = databaseConfig;
let db; let created = false;
try {
  db = await mysql.createConnection({ ...connection, port: Number(connection.port), connectTimeout: 4000 });
  await db.query(`CREATE DATABASE \`${database}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci`); created = true;
  const prisma = path.join(projectRoot, 'node_modules/prisma/build/index.js');
  const result = spawnSync(process.execPath, [prisma, 'migrate', 'deploy', '--config', 'prisma.config.ts'], { cwd: projectRoot, env: { ...process.env, PRISMA_DATABASE_NAME: database }, encoding: 'utf8', windowsHide: true });
  assert.equal(result.status, 0, `Prisma migrate deploy falhou: ${result.stderr}`);
  const store = tenantStore(tenantId);
  let now = Date.parse('2026-11-05T10:00:00-03:00'); const clock = () => now;
  await registerStation(store, { id: 'TEST-SQL', locality: 'Belém', mode: 'DEMO', demoScenario: 'critical' }, 'test');
  const agenda = new Agenda(store, clock);
  const h = await agenda.save({ label: 'Teste isolado', locality: 'Belém', room: 'Sala 1', stationId: 'TEST-SQL', responsible: 'Teste', startsAt: '2026-11-05T10:30:00-03:00', mode: 'DEMO' }, 'test');
  const createWorker = () => new HearingScheduler({ store, clock, escalation: new EscalationOutbox({ store, clock }) });
  await Promise.all([createWorker().tick(), createWorker().tick()]);
  assert.equal((await store.get('job', `${h.id}:1`)).attempts, 1);
  now += 16 * 60000; await createWorker().tick();
  assert.equal((await store.list('escalation')).length, 1);
  assert.equal((await store.list('escalation'))[0].status, 'SENT');
  await createWorker().tick(); assert.equal((await store.list('escalation')).length, 1);
  assert.ok((await store.auditLog(h.id)).length > 3);
  console.log('PASS MariaDB: migrations Prisma, agenda, concorrência entre workers, evidências, escalação e recuperação sem duplicação.');
} catch (e) { console.error('FAIL MariaDB:', e.code || e.message); process.exitCode = 1; }
finally {
  await closePreventionPools();
  // Only the UUID database generated by this test may be dropped.
  if (db && created && database === tenantDatabaseName(tenantId)) await db.query(`DROP DATABASE \`${database}\``);
  await db?.end();
}
